// Command worker is a minimal real node for the Musubi Control Hub. It
// registers over POST /v1/register, heartbeats, pulls commands with
// command.pull and reports results with command.complete. It needs only the
// standard library: any language that can speak JSON-RPC can do the same.
//
// Usage:
//
//	go run . -url http://127.0.0.1:8080 -id w-1 -token secret
//
// Supported demo methods: echo, fail, sleep, uptime. Anything else is reported
// as failed with -32601.
package main

import (
	"bytes"
	"context"
	"encoding/json"
	"flag"
	"fmt"
	"log"
	"net/http"
	"os"
	"os/signal"
	"strings"
	"syscall"
	"time"
)

type client struct {
	url   string
	token string
	id    int
	http  *http.Client
}

type rpcError struct {
	Code    int             `json:"code"`
	Message string          `json:"message"`
	Data    json.RawMessage `json:"data,omitempty"`
}

func (e *rpcError) Error() string { return fmt.Sprintf("rpc %d: %s", e.Code, e.Message) }

type rpcResponse struct {
	JSONRPC string          `json:"jsonrpc"`
	ID      int             `json:"id"`
	Result  json.RawMessage `json:"result"`
	Error   *rpcError       `json:"error"`
}

func (c *client) call(ctx context.Context, method string, params any) (json.RawMessage, error) {
	c.id++
	body, err := json.Marshal(map[string]any{
		"jsonrpc": "2.0", "id": c.id, "method": method, "params": params,
	})
	if err != nil {
		return nil, err
	}
	req, err := http.NewRequestWithContext(ctx, http.MethodPost, c.url+"/v1/rpc", bytes.NewReader(body))
	if err != nil {
		return nil, err
	}
	req.Header.Set("Content-Type", "application/json")
	if c.token != "" {
		req.Header.Set("Authorization", "Bearer "+c.token)
	}
	res, err := c.http.Do(req)
	if err != nil {
		return nil, err
	}
	defer res.Body.Close()
	var out rpcResponse
	if err := json.NewDecoder(res.Body).Decode(&out); err != nil {
		return nil, fmt.Errorf("decode response (HTTP %d): %w", res.StatusCode, err)
	}
	if out.Error != nil {
		return nil, out.Error
	}
	return out.Result, nil
}

type command struct {
	ID     string         `json:"id"`
	NodeID string         `json:"node_id"`
	Method string         `json:"method"`
	Params map[string]any `json:"params"`
}

type pullResult struct {
	Commands []command `json:"commands"`
}

func main() {
	url := flag.String("url", "http://127.0.0.1:8080", "hub base URL")
	token := flag.String("token", "", "bearer token (token/basic mode)")
	id := flag.String("id", "", "node id (generated by the hub when empty)")
	name := flag.String("name", "", "node display name")
	caps := flag.String("capabilities", "echo,sleep,uptime", "comma-separated capabilities")
	tags := flag.String("tags", "worker,linux", "comma-separated tags")
	interval := flag.Duration("heartbeat", 3*time.Second, "heartbeat interval")
	flag.Parse()

	c := &client{url: strings.TrimRight(*url, "/"), token: *token, http: &http.Client{Timeout: 45 * time.Second}}
	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	defer stop()

	regBody := map[string]any{
		"name":         first(*name, *id),
		"capabilities": split(*caps),
		"tags":         split(*tags),
		"metadata":     map[string]any{"runtime": "go-worker"},
	}
	if *id != "" {
		regBody["id"] = *id
	}
	reg, err := json.Marshal(regBody)
	if err != nil {
		log.Fatal(err)
	}
	req, err := http.NewRequestWithContext(ctx, http.MethodPost, c.url+"/v1/register", bytes.NewReader(reg))
	if err != nil {
		log.Fatal(err)
	}
	req.Header.Set("Content-Type", "application/json")
	if c.token != "" {
		req.Header.Set("Authorization", "Bearer "+c.token)
	}
	res, err := c.http.Do(req)
	if err != nil {
		log.Fatalf("register: %v", err)
	}
	defer res.Body.Close()
	var node struct {
		ID     string `json:"id"`
		Status string `json:"status"`
	}
	if res.StatusCode != http.StatusOK {
		var e struct {
			Error *rpcError `json:"error"`
		}
		_ = json.NewDecoder(res.Body).Decode(&e)
		log.Fatalf("register failed: HTTP %d %+v", res.StatusCode, e.Error)
	}
	if err := json.NewDecoder(res.Body).Decode(&node); err != nil {
		log.Fatalf("register decode: %v", err)
	}
	nodeID := node.ID
	log.Printf("registered node %s (%s)", nodeID, node.Status)

	// Heartbeat keeps the watchdog from marking us offline; pull will then
	// never see node.offline.
	go func() {
		t := time.NewTicker(*interval)
		defer t.Stop()
		for {
			select {
			case <-ctx.Done():
				return
			case <-t.C:
				if _, err := c.call(ctx, "node.heartbeat", map[string]any{"node_id": nodeID}); err != nil {
					log.Printf("heartbeat: %v", err)
				}
			}
		}
	}()

	defer func() {
		ctx, cancel := context.WithTimeout(context.Background(), 2*time.Second)
		defer cancel()
		if _, err := c.call(ctx, "node.unregister", map[string]any{"node_id": nodeID}); err != nil {
			log.Printf("unregister: %v", err)
		}
	}()

	log.Printf("pulling commands (Ctrl-C to stop)")
	for {
		select {
		case <-ctx.Done():
			return
		default:
		}
		raw, err := c.call(ctx, "command.pull", map[string]any{"node_id": nodeID, "limit": 4, "wait": 5000})
		if err != nil {
			if ctx.Err() != nil {
				return
			}
			log.Printf("pull: %v", err)
			time.Sleep(time.Second)
			continue
		}
		var pulled pullResult
		if err := json.Unmarshal(raw, &pulled); err != nil {
			log.Printf("pull decode: %v", err)
			continue
		}
		for _, cmd := range pulled.Commands {
			go runOne(ctx, c, nodeID, cmd)
		}
	}
}

func runOne(ctx context.Context, c *client, nodeID string, cmd command) {
	start := time.Now()
	status, result, rerr := execute(ctx, cmd)
	params := map[string]any{
		"node_id":    nodeID,
		"command_id": cmd.ID,
		"status":     status,
	}
	if rerr != nil {
		params["error"] = map[string]any{"code": rerr.Code, "message": rerr.Message}
	} else {
		params["result"] = result
	}
	if _, err := c.call(context.Background(), "command.complete", params); err != nil {
		log.Printf("complete %s: %v", cmd.ID, err)
		return
	}
	log.Printf("command %s method=%s status=%s in %s", cmd.ID, cmd.Method, status, time.Since(start).Round(time.Millisecond))
}

func execute(ctx context.Context, cmd command) (string, any, *rpcError) {
	switch cmd.Method {
	case "echo":
		return "succeeded", cmd.Params, nil
	case "fail":
		return "failed", nil, &rpcError{Code: -32000, Message: "worker: simulated failure"}
	case "sleep":
		ms := 0
		if v, ok := cmd.Params["ms"].(float64); ok {
			ms = int(v)
		}
		if ms < 0 {
			ms = 0
		}
		select {
		case <-time.After(time.Duration(ms) * time.Millisecond):
			return "succeeded", map[string]any{"slept": ms}, nil
		case <-ctx.Done():
			return "cancelled", nil, nil
		}
	case "uptime":
		return "succeeded", map[string]any{"uptime_seconds": int(time.Since(startedAt).Seconds())}, nil
	default:
		return "failed", nil, &rpcError{Code: -32601, Message: "method not found: " + cmd.Method}
	}
}

var startedAt = time.Now()

func split(s string) []string {
	var out []string
	for _, p := range strings.Split(s, ",") {
		if p = strings.TrimSpace(p); p != "" {
			out = append(out, p)
		}
	}
	return out
}

func first(a, b string) string {
	if a != "" {
		return a
	}
	return b
}
